def _short_phrase(question):
    q = question.replace('؟', ' ').replace('?', ' ').replace('«', ' ').replace('»', ' ')
    q = ' '.join(q.split())
    words = [w for w in q.split(' ') if len(w) > 2 and w not in ('چطور', 'چگونه', 'کجا', 'چیست', 'که', 'را', 'به', 'با', 'از', 'های', 'شود', 'کنم', 'بدهد', 'چیزی')]
    phrase = ' '.join(words[:3]).strip()
    return phrase if 3 <= len(phrase) <= 40 else ''


